def _render_pdf_bytes(lines: list[str]) -> bytes:
    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=(595, 842))
    y = 800
    for line in lines:
        pdf.drawString(50, y, line)
        y -= 18
    pdf.save()
    return buffer.getvalue()


def _write_encrypted(
    lines: list[str], password: str, path: Path, metadata: dict[str, str] | None = None
) -> None:
    plain_bytes = _render_pdf_bytes(lines)
    reader = PdfReader(BytesIO(plain_bytes))
    writer = PdfWriter()
    for page in reader.pages:
        writer.add_page(page)
    if metadata:
        writer.add_metadata(metadata)
    writer.encrypt(user_password=password)
    with open(path, "wb") as fh:
        writer.write(fh)


def _write_plain(lines: list[str], path: Path) -> None:
    path.write_bytes(_render_pdf_bytes(lines))


